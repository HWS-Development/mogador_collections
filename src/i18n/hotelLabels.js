export function translateDestinationName(name, lang) {
  return destinationNames[lang]?.[name] || name
}

export function translateHotelLabel(value, lang) {
  if (!value || lang === 'fr') return value
  let translated = String(value)
  const replacements = lang === 'ar' ? arabicReplacements : englishReplacements
  replacements.forEach(([pattern, replacement]) => {
    translated = translated.replace(pattern, replacement)
  })
  Object.entries(destinationNames[lang] || {}).forEach(([source, replacement]) => {
    translated = translated.replace(new RegExp(source, 'gi'), replacement)
  })
  return translated
}
